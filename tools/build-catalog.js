#!/usr/bin/env node
/* Generates every catalog from the games themselves (filesystem discovery + metadata embedded in each game):
 *   catalog.js                         window.GDL_CATALOG  — the arcade launcher's data
 *   PhoneGameLab{,2}/shared/catalog.js  window.LAB_GAMES    — each phone lab's own launcher data
 * Standalone games:  <title>, <meta name="description">, <meta name="gdl:genre">, <meta name="gdl:controls">
 * Phone games:       Lab.init({ title, tagline, category })   (untransformed prototypes fall back to tools/legacy-phone-catalog.json)
 * Review scores (docs/reviews/<id>.md front-matter) and thumbnails (thumbs/) are attached when present.
 *   node tools/build-catalog.js [--check]     (--check: exit 1 if generated files are stale)
 */
const fs = require('fs'), path = require('path');
const { discover, ROOT } = require('./discover');
const legacy = JSON.parse(fs.readFileSync(path.join(__dirname, 'legacy-phone-catalog.json'), 'utf8'));
const check = process.argv.includes('--check');
const unesc = s => s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&mdash;/g, '—').trim();
const meta = (src, name) => { const m = src.match(new RegExp('<meta\\s+name=["\']' + name + '["\']\\s+content=["\']([^"\']*)["\']', 'i')); return m ? unesc(m[1]) : ''; };
const str = (src, key) => { const m = src.match(new RegExp('\\b' + key + '\\s*:\\s*(?:"((?:[^"\\\\]|\\\\.)*)"|\'((?:[^\'\\\\]|\\\\.)*)\'|`([^`]*)`)')); return m ? (m[1] ?? m[2] ?? m[3]).replace(/\\(["'])/g, '$1') : ''; };
const list = s => s.split(',').map(x => x.trim()).filter(Boolean);
function review(id) {
  const f = path.join(ROOT, 'docs/reviews', id.replace(/^games\//, 'games/') + '.md'); if (!fs.existsSync(f)) return {};
  const fm = fs.readFileSync(f, 'utf8').match(/^---\n([\s\S]*?)\n---/); if (!fm) return {};
  const o = {}; for (const l of fm[1].split('\n')) { const m = l.match(/^(\w+):\s*(.*?)\s*(#.*)?$/); if (m) o[m[1]] = m[2]; } return o;
}
const games = [];
for (const g of discover()) {
  if (g.collection === 'archive') continue;
  const src = fs.readFileSync(path.join(ROOT, g.path), 'utf8'), rv = review(g.id), e = { id: g.id, path: g.path, collection: g.collection };
  if (g.collection === 'arcade') {
    e.title = unesc((src.match(/<title>([^<]*)<\/title>/i) || [, g.id])[1]);
    e.desc = meta(src, 'description'); e.genre = list(meta(src, 'gdl:genre') || 'Arcade');
    e.controls = list(meta(src, 'gdl:controls')); if (!e.controls.length) { if (/touchstart|pointerdown/.test(src)) e.controls.push('touch'); if (/mousedown|pointerdown|click/.test(src)) e.controls.push('mouse'); if (/keydown/.test(src)) e.controls.push('keyboard'); }
  } else {
    const init = src.slice(src.indexOf('Lab.init('), src.indexOf('Lab.init(') + 1600), slug = g.id.split('/')[1], lg = legacy[g.id] || {};
    const v2 = /Lab\.boot\(\)/.test(src);
    e.title = str(init, 'title') || lg.t || slug; e.desc = str(init, 'tagline') || lg.d || str(init, 'instructions');
    e.genre = [str(init, 'category') || (g.collection === 'PhoneGameLab' ? lg.cat : '') || 'Minigame'];
    e.controls = ['touch', 'mouse']; if (/onKey|input\.keys|axisX|pressed\(/.test(src)) e.controls.push('keyboard');
    e.n = lg.n || (parseInt(slug, 10) || undefined); e.v2 = v2;
  }
  if (rv.score) e.score = +rv.score; if (rv.status) e.status = rv.status;
  const thumb = 'thumbs/' + g.id.replace(/\//g, '--') + '.jpg'; if (fs.existsSync(path.join(ROOT, thumb))) e.thumb = thumb;
  const strip = thumb.replace(/\.jpg$/, '.strip.jpg'); if (fs.existsSync(path.join(ROOT, strip))) e.strip = strip;
  games.push(e);
}
const outputs = {};
outputs['catalog.js'] = '/* GENERATED by tools/build-catalog.js — do not edit. */\nwindow.GDL_CATALOG = ' + JSON.stringify({ count: games.length, games }, null, 1) + ';\n';
for (const lab of ['PhoneGameLab', 'PhoneGameLab2']) {
  const mine = games.filter(g => g.collection === lab).sort((a, b) => (a.n || 999) - (b.n || 999) || a.title.localeCompare(b.title));
  const cats = []; for (const g of mine) { const c = g.genre[0]; let grp = cats.find(x => x.cat === c); if (!grp) cats.push(grp = { cat: c, items: [] }); grp.items.push({ n: g.n, slug: g.id.split('/')[1], t: g.title, d: g.desc, v2: g.v2 || undefined, score: g.score, thumb: g.thumb ? '../' + g.thumb : undefined }); }
  outputs[lab + '/shared/catalog.js'] = '/* GENERATED by tools/build-catalog.js — do not edit. */\nwindow.LAB_GAMES = ' + JSON.stringify(cats, null, 1) + ';\n';
}
let stale = 0;
for (const [f, body] of Object.entries(outputs)) {
  const p = path.join(ROOT, f), cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
  if (cur !== body) { if (check) { console.error('stale:', f); stale = 1; } else { fs.writeFileSync(p, body); console.log('wrote', f); } }
}
if (!check) console.log(games.length + ' games catalogued (' + games.filter(g => g.score).length + ' reviewed)');
process.exit(stale);
